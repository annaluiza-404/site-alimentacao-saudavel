CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE IF NOT EXISTS usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100)  NOT NULL,
    email       VARCHAR(150)  NOT NULL UNIQUE,
    cpf         VARCHAR(14)   UNIQUE,
    senha       VARCHAR(72)   NOT NULL,
    preferencia VARCHAR(30),
    admin       BOOLEAN       NOT NULL DEFAULT FALSE,
    criado_em   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_usuario_cpf CHECK (cpf IS NULL OR cpf ~ '^[0-9]{3}\.[0-9]{3}\.[0-9]{3}-[0-9]{2}$')
);

CREATE TABLE IF NOT EXISTS enderecos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT        NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    cep         VARCHAR(9)    NOT NULL,
    logradouro  VARCHAR(200)  NOT NULL,
    numero      VARCHAR(20)   NOT NULL,
    complemento VARCHAR(100),
    bairro      VARCHAR(100)  NOT NULL,
    cidade      VARCHAR(100)  NOT NULL,
    estado      CHAR(2)       NOT NULL,
    CONSTRAINT ck_endereco_cep CHECK (cep ~ '^[0-9]{5}-[0-9]{3}$'),
    CONSTRAINT ck_endereco_estado CHECK (estado ~ '^[A-Z]{2}$')
);

CREATE TABLE IF NOT EXISTS marcas (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS categorias (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL UNIQUE,
    tipo  VARCHAR(12)  NOT NULL DEFAULT 'produto',
    CONSTRAINT ck_categoria_tipo CHECK (tipo IN ('produto', 'restricao'))
);

CREATE TABLE IF NOT EXISTS produtos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca_id     BIGINT        NOT NULL REFERENCES marcas(id),
    nome         VARCHAR(100)  NOT NULL UNIQUE,
    descricao    VARCHAR(500),
    preco        DECIMAL(10,2) NOT NULL,
    estoque_qtd  INTEGER       NOT NULL DEFAULT 0,
    imagem_url   VARCHAR(255),
    destaque     BOOLEAN       NOT NULL DEFAULT FALSE,
    ativo        BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em    TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_produto_preco CHECK (preco >= 0),
    CONSTRAINT ck_produto_estoque CHECK (estoque_qtd >= 0)
);

CREATE TABLE IF NOT EXISTS produto_categoria (
    produto_id   BIGINT NOT NULL REFERENCES produtos(id) ON DELETE CASCADE,
    categoria_id BIGINT NOT NULL REFERENCES categorias(id) ON DELETE CASCADE,
    CONSTRAINT pk_produto_categoria PRIMARY KEY (produto_id, categoria_id)
);

CREATE TABLE IF NOT EXISTS cupons (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(50)   NOT NULL UNIQUE,
    valor_desconto  DECIMAL(10,2) NOT NULL,
    tipo_desconto   VARCHAR(20)   NOT NULL,
    minimo_subtotal DECIMAL(10,2) NOT NULL DEFAULT 0,
    data_validade   DATE          NOT NULL,
    ativo           BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_cupom_tipo CHECK (tipo_desconto IN ('percentual', 'fixo', 'frete')),
    CONSTRAINT ck_cupom_valor CHECK (valor_desconto >= 0),
    CONSTRAINT ck_cupom_minimo CHECK (minimo_subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS pedidos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT        NOT NULL REFERENCES usuarios(id),
    cupom_id        BIGINT        REFERENCES cupons(id),
    subtotal        DECIMAL(10,2) NOT NULL,
    frete           DECIMAL(10,2) NOT NULL DEFAULT 0,
    desconto        DECIMAL(10,2) NOT NULL DEFAULT 0,
    total           DECIMAL(10,2) NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'pendente',
    forma_pagamento VARCHAR(20)   NOT NULL,
    cep_entrega     VARCHAR(9)    NOT NULL,
    criado_em       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_pedido_total CHECK (total >= 0),
    CONSTRAINT ck_pedido_status CHECK (status IN ('pendente', 'pago', 'enviado', 'entregue', 'cancelado')),
    CONSTRAINT ck_pedido_pagamento CHECK (forma_pagamento IN ('cartao', 'pix', 'boleto'))
);

CREATE TABLE IF NOT EXISTS itens_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT        NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    produto_id     BIGINT        NOT NULL REFERENCES produtos(id),
    quantidade     INTEGER       NOT NULL,
    preco_unitario DECIMAL(10,2) NOT NULL,
    CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco CHECK (preco_unitario >= 0),
    CONSTRAINT uq_item UNIQUE (pedido_id, produto_id)
);

CREATE TABLE IF NOT EXISTS receitas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo     VARCHAR(150) NOT NULL,
    categoria  VARCHAR(50)  NOT NULL,
    texto      TEXT         NOT NULL,
    imagem     VARCHAR(255) NOT NULL,
    criado_em  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ingrediente_receita (
    receita_id BIGINT       NOT NULL REFERENCES receitas(id) ON DELETE CASCADE,
    produto_id BIGINT       NOT NULL REFERENCES produtos(id),
    quantidade VARCHAR(50)  NOT NULL,
    CONSTRAINT pk_ingrediente_receita PRIMARY KEY (receita_id, produto_id)
);

CREATE INDEX IF NOT EXISTS idx_produto_marca ON produtos(marca_id) WHERE ativo;
CREATE INDEX IF NOT EXISTS idx_pedido_usuario ON pedidos(usuario_id);
CREATE INDEX IF NOT EXISTS idx_item_produto ON itens_pedido(produto_id);
CREATE INDEX IF NOT EXISTS idx_produto_categoria_cat ON produto_categoria(categoria_id);
